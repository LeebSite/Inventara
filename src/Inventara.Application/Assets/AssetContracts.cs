using Inventara.Domain.Enums;

namespace Inventara.Application.Assets;

/// <summary>Filters, pagination, and sorting options for the asset list.</summary>
public sealed record AssetListQuery
{
    /// <summary>Searches asset names and codes.</summary>
    public string? Search { get; init; }

    /// <summary>Filters by asset status.</summary>
    public AssetStatus? Status { get; init; }

    /// <summary>Filters by category ID.</summary>
    public Guid? CategoryId { get; init; }

    /// <summary>Filters by location ID.</summary>
    public Guid? LocationId { get; init; }

    /// <summary>One-based page number.</summary>
    public int Page { get; init; } = 1;

    /// <summary>Maximum records returned per page.</summary>
    public int PageSize { get; init; } = 10;

    /// <summary>Field used to sort the matching assets.</summary>
    public string? SortBy { get; init; }

    /// <summary>Sort direction, either asc or desc.</summary>
    public string SortDir { get; init; } = "asc";
}

/// <summary>Asset data returned by list and write endpoints.</summary>
public sealed record AssetResponse(
    Guid Id,
    string AssetCode,
    string Name,
    Guid CategoryId,
    string CategoryName,
    Guid LocationId,
    string LocationName,
    Guid? VendorId,
    string? VendorName,
    string? SerialNumber,
    DateTimeOffset PurchaseDate,
    decimal PurchasePrice,
    AssetCondition Condition,
    AssetStatus Status,
    string? PhotoUrl,
    string? Notes);

/// <summary>Asset details, including the most recent loan.</summary>
public sealed record AssetDetailResponse(
    AssetResponse Asset,
    AssetRecentLoanResponse? MostRecentLoan);

/// <summary>The most recent loan recorded for an asset.</summary>
public sealed record AssetRecentLoanResponse(
    Guid Id,
    Guid BorrowerId,
    DateTimeOffset RequestedAt,
    DateTimeOffset LoanDate,
    DateTimeOffset DueDate,
    DateTimeOffset? ReturnDate,
    LoanStatus Status,
    string Purpose);

/// <summary>Fields used to create an asset; the asset code is generated by the API.</summary>
public sealed record CreateAssetRequest
{
    /// <summary>Asset name.</summary>
    public required string Name { get; init; }

    /// <summary>Category ID.</summary>
    public required Guid CategoryId { get; init; }

    /// <summary>Location ID.</summary>
    public required Guid LocationId { get; init; }

    /// <summary>Optional vendor ID.</summary>
    public Guid? VendorId { get; init; }

    /// <summary>Optional manufacturer serial number.</summary>
    public string? SerialNumber { get; init; }

    /// <summary>Date the asset was purchased.</summary>
    public required DateTimeOffset PurchaseDate { get; init; }

    /// <summary>Purchase price in the configured currency.</summary>
    public required decimal PurchasePrice { get; init; }

    /// <summary>Current physical condition.</summary>
    public required AssetCondition Condition { get; init; }

    /// <summary>Optional notes.</summary>
    public string? Notes { get; init; }
}

/// <summary>Fields used to update an asset without changing its generated code.</summary>
public sealed record UpdateAssetRequest
{
    /// <summary>Asset name.</summary>
    public required string Name { get; init; }

    /// <summary>Category ID.</summary>
    public required Guid CategoryId { get; init; }

    /// <summary>Location ID.</summary>
    public required Guid LocationId { get; init; }

    /// <summary>Optional vendor ID.</summary>
    public Guid? VendorId { get; init; }

    /// <summary>Optional manufacturer serial number.</summary>
    public string? SerialNumber { get; init; }

    /// <summary>Date the asset was purchased.</summary>
    public required DateTimeOffset PurchaseDate { get; init; }

    /// <summary>Purchase price in the configured currency.</summary>
    public required decimal PurchasePrice { get; init; }

    /// <summary>Current physical condition.</summary>
    public required AssetCondition Condition { get; init; }

    /// <summary>Optional notes.</summary>
    public string? Notes { get; init; }
}

/// <summary>File metadata and content submitted for an asset photo.</summary>
public sealed record UploadAssetPhotoRequest(
    string FileName,
    string ContentType,
    long Length,
    Stream Content);

/// <summary>Data written to the asset export worksheet.</summary>
public sealed record AssetExportRow(
    string AssetCode,
    string Name,
    string Category,
    string Location,
    string? Vendor,
    string? SerialNumber,
    DateTime PurchaseDate,
    decimal PurchasePrice,
    AssetCondition Condition,
    AssetStatus Status,
    string? PhotoUrl,
    string? Notes);
